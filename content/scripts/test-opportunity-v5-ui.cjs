const { VIEWPORTS, settleViewport } = require('./opportunity-ui-browser-support.cjs');
const assert = require('node:assert/strict');
const fs = require('node:fs');
const path = require('node:path');
const { gunzipSync } = require('node:zlib');
const { chromium } = require('playwright');
(async () => {
    const { attachOpportunitySales, rankCommercialOpportunities } = await import('../js/core/market-opportunity-commerce.mjs');
    const { rankOpportunityPresentation } = await import('../js/core/market-opportunity-quality.mjs');
    const { opportunityTradePrices, calculateTradeScenario } = await import('../js/core/market-trade-scenario.mjs');
    const dir = 'docs/opportunity-v5';
    const read = name => JSON.parse(gunzipSync(fs.readFileSync(`${dir}/${name}.json.gz`)));
    const scan = read('baseline-scan'), history = read('sales-history');
    const anchors = new Map(history.rows.map(row => [`${row.item_id}|${row.location}|${row.quality}`, { ...row, fetchedAt: history.fetchedAt }]));
    scan.eligibleCandidates = attachOpportunitySales(scan.eligibleCandidates, (item, city, quality) => anchors.get(`${item}|${city}|${quality}`), Date.parse(history.fetchedAt));
    scan.opportunities = scan.eligibleCandidates;
    const groups = rankCommercialOpportunities(rankOpportunityPresentation(scan.eligibleCandidates, { calibration: scan.qualityCalibration }), { calibration: scan.qualityCalibration });
    const rates = JSON.parse(fs.readFileSync('data/economy-constants.json'));
    const rate = key => Number(rates.find(row => row.key === key).value);
    const fees = { setupFeeRate: rate('setup_fee'), taxPremiumRate: rate('tax_premium'), taxFreeRate: rate('tax_free') };
    const browser = await chromium.launch({ channel: 'chrome', headless: true });
    try {
        const context = await browser.newContext({ viewport: { width: 1440, height: 1000 }, permissions: ['clipboard-read', 'clipboard-write'] });
        await context.addInitScript(() => {
            localStorage.setItem('albiontools.v4.dailyBonusRedirectAt', String(Date.now()));
            localStorage.setItem('albiontools.v4.settings', JSON.stringify({ dataSync: false, server: 'europe', premium: true }));
            localStorage.setItem('opp-layout', 'cards');
        });
        const page = await context.newPage(), errors = [], origin = 'http://localhost:3013';
        page.on('pageerror', error => errors.push(error.message));
        await page.route('**/*', route => {
            const url = new URL(route.request().url());
            if (url.origin !== origin) return route.abort();
            let relative = decodeURIComponent(url.pathname).replace(/^\//, '');
            if (!path.extname(relative)) relative = relative.replace(/\/$/, '') + '/index.html';
            const file = path.resolve(relative);
            if (!file.startsWith(process.cwd() + path.sep) || !fs.existsSync(file)) return route.fulfill({ status: 404, body: '' });
            const types = { '.html': 'text/html', '.js': 'text/javascript', '.mjs': 'text/javascript', '.json': 'application/json', '.css': 'text/css', '.svg': 'image/svg+xml', '.png': 'image/png', '.webp': 'image/webp' };
            return route.fulfill({ body: fs.readFileSync(file), contentType: types[path.extname(file)] || 'application/octet-stream' });
        });
        await page.route('**/api/v1/market/opportunities?**', route => route.fulfill({ json: scan }));
        await page.route('**/api/v1/market/opportunity-series?**', route => route.fulfill({ json: { buy: { points: [] }, sell: { points: [] } } }));
        await page.goto(origin + '/pages/tools/opportunities/');
        await page.locator('.opp-card').first().waitFor();
        assert.equal(await page.locator('.opp-card').count(), groups.length);
        const card = page.locator('.opp-card').filter({ hasText: 'kaynak rota' }).first();
        const id = await card.getAttribute('data-opportunity');
        const group = groups.find(row => row.id === id);
        assert.ok(group.routeOptions.length > 1);
        const name = card.locator('[data-copy-item-name]');
        const copyName = await name.getAttribute('data-copy-item-name');
        await name.click();
        assert.equal(await page.evaluate(() => navigator.clipboard.readText()), copyName);
        assert.equal(await page.locator('[data-opportunities-dialog]').evaluate(element => element.open), false);
        await card.locator('.opp-card-go').click();
        const sheet = page.locator('[data-opportunities-sheet]');
        await sheet.locator('[data-scenario-field="quantity"]').waitFor();
        assert.ok((await sheet.locator('[data-scenario-result]').innerText()).includes('miktar girin'));
        await sheet.locator('[data-scenario-field="quantity"]').fill('100');
        await sheet.locator('[data-scenario-options] summary').click();
        await sheet.locator('[data-scenario-field="fixedCost"]').fill('1000');
        const expected = calculateTradeScenario({ ...opportunityTradePrices(group.primary), quantity: 100, fixedCost: 1000, perUnitCost: 0, fees });
        const readNet = () => sheet.locator('[data-scenario-result] tr').filter({ hasText: 'Toplam teorik net kâr' }).locator('td').innerText();
        const parseSilver = text => Number(text.replace(/[^\d,−-]/g, '').replace(',', '.').replace('−', '-'));
        assert.ok(Math.abs(parseSilver(await readNet()) - expected.net) <= 1.01);
        assert.equal(await sheet.locator('[data-opportunity-route]').count(), group.routeOptions.length);
        await page.screenshot({ path: `${dir}/scenario-desktop.png`, fullPage: true });
        const alternative = group.routeOptions[1];
        await sheet.locator('[data-route-options] summary').click();
        await sheet.locator('[data-opportunity-route]').nth(1).click();
        await page.waitForFunction(value => document.querySelector('[data-scenario-field="buyPrice"]')?.value === value, String(opportunityTradePrices(alternative.primary).buyPrice));
        assert.equal(await sheet.locator('[data-scenario-field="quantity"]').inputValue(), '100');
        assert.equal(await sheet.locator('[data-scenario-field="fixedCost"]').inputValue(), '1000');
        await settleViewport(page, { width: 390, height: 844 });
        await sheet.locator('[data-opportunity-scenario]').scrollIntoViewIfNeeded();
        await page.screenshot({ path: `${dir}/scenario-mobile.png`, fullPage: true });
        const widths = await sheet.evaluate(element => ({ width: element.clientWidth, scroll: element.scrollWidth }));
        assert.ok(widths.scroll <= widths.width + 1, `mobile sheet overflow ${JSON.stringify(widths)}`);
        await page.locator('[data-opportunities-close]').click();
        await page.locator('[data-list-mode="quantity"]').click();
        await page.locator('.opp-card').first().waitFor();
        assert.equal(await page.locator('.opp-card').count(), groups.filter(row => row.commercialLane === 'commercial').length);
        assert.deepEqual(errors, []);
        console.log('Chrome V5: real frozen data, route groups/alternatives, clipboard, blank quantity, scenario arithmetic, persisted inputs and desktop/mobile layout passed.');
    } finally { await browser.close(); }
})().catch(error => { console.error(error); process.exit(1); });
