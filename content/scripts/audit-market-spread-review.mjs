import assert from 'node:assert/strict';
import {readFileSync,writeFileSync,unlinkSync,createReadStream} from 'node:fs';
import {gunzipSync,createGunzip,gzipSync} from 'node:zlib';
import {createInterface} from 'node:readline';
import {pathToFileURL} from 'node:url';
import {resolve} from 'node:path';
import {performance} from 'node:perf_hooks';
import {QuoteHistoryRepository} from './quote-history-repository.mjs';
import {OrderPriceHistory} from '../js/core/order-price-history.mjs';
import {AODP_HISTORY_POLICY} from '../js/core/market-history-config.mjs';
import {scanQuoteBooks} from '../js/core/market-opportunity-scan.mjs';
const root='docs/market-spread-review', dir=root+'/snapshot';
const read=name=>JSON.parse(gunzipSync(readFileSync(dir+'/'+name+'.gz')));
let archive=read('.aodp-quote-history.json');
const now=Date.parse(JSON.parse(readFileSync(dir+'/manifest.json')).asOf);
const servers=JSON.parse(readFileSync('data/price-servers.json')).map(r=>r.code);
const repository=Object.create(QuoteHistoryRepository.prototype);
Object.assign(repository,{history:new OrderPriceHistory({servers,source:'aodp-current',policy:AODP_HISTORY_POLICY}),anchors:new Map(archive.anchors),current:new Map(archive.current),audits:[],sequence:archive.sequence,pending:[],policy:{}});
repository.history.restore(archive.history,now);
archive=null;
for await(const line of createInterface({input:createReadStream(dir+'/.aodp-quote-history.json.journal.gz').pipe(createGunzip()),crlfDelay:Infinity})) {
 if(!line)continue;const tx=JSON.parse(line);if(tx.sequence<=repository.sequence)continue;
 assert.equal(tx.sequence,repository.sequence+1);for(const event of tx.events)repository.apply(event,now);repository.sequence=tx.sequence;
}
repository.prune(now);
let packets=read('.price-order-history.json');
const packetHistory=new OrderPriceHistory({servers});packetHistory.restore(packets,now);packets=null;
if(global.gc)global.gc();
const heapBeforeScansMb=process.memoryUsage().heapUsed/1048576;
const rates=JSON.parse(readFileSync('data/economy-constants.json'));
const rate=key=>Number(rates.find(r=>r.key===key).value);
const fees={setupFeeRate:rate('setup_fee'),taxPremiumRate:rate('tax_premium'),taxFreeRate:rate('tax_free')};
const args={server:'europe',repository,packetHistory,now,fees,includeCandidates:true};
let source=readFileSync('content/js/core/market-opportunity-scan.mjs','utf8');
source=source.replace(/        let history = \{ buy: \[\], sell: \[\] };[\s\S]*?if \(row\.spreadRealism\.reasons\.length\).*?\n/,'');
source=source.replace(/from '(\.\/[^']+)'/g,(_,p)=>`from '${pathToFileURL(resolve('content/js/core',p)).href}'`);
const temporary=resolve(root+'/baseline-scan.mjs');writeFileSync(temporary,source);
let baseline;try { baseline=await import(pathToFileURL(temporary).href); } finally { unlinkSync(temporary); }
const measure=fn=>{const t=performance.now();const value=fn();return {value,elapsedMs:performance.now()-t,heapUsedMb:process.memoryUsage().heapUsed/1048576};};
let measured=measure(()=>baseline.scanQuoteBooks(args));const before=measured.value,oldMs=measured.elapsedMs,oldHeapMb=measured.heapUsedMb;
if(global.gc)global.gc();
const baselineLiveHeapMb=process.memoryUsage().heapUsed/1048576;
measured=measure(()=>scanQuoteBooks(args));const after=measured.value,coldMs=measured.elapsedMs,coldHeapMb=measured.heapUsedMb;
const canonical=rows=>rows.map(({spreadReview,...row})=>row);
assert.deepEqual(canonical(before.eligibleCandidates),canonical(after.eligibleCandidates));
if(global.gc)global.gc();
const coldLiveHeapMb=process.memoryUsage().heapUsed/1048576;
measured=measure(()=>scanQuoteBooks(args));const warm=measured.value,warmMs=measured.elapsedMs,warmHeapMb=measured.heapUsedMb;
assert.deepEqual(after.eligibleCandidates,warm.eligibleCandidates);
if(global.gc)global.gc();
const warmLiveHeapMb=process.memoryUsage().heapUsed/1048576;
const local=after.eligibleCandidates.filter(r=>r.strategies.some(s=>s.id==='local-make'));
const count=(rows,fn)=>rows.reduce((a,r)=>{const k=fn(r);a[k]=(a[k]||0)+1;return a;},{});
const report={asOf:new Date(now).toISOString(),sequence:repository.sequence,candidates:after.eligibleCandidates.length,local:local.length,previous:count(local,r=>r.spreadRealism.classification),next:count(local,r=>r.spreadReview.classification),pairedSamples:count(local,r=>r.spreadReview.samples),decisionsUnchanged:true,oldMs,coldMs,warmMs,heapUsedMb:{beforeScans:heapBeforeScansMb,oldAfter:oldHeapMb,baselineRetained:baselineLiveHeapMb,coldAfter:coldHeapMb,coldRetained:coldLiveHeapMb,warmAfter:warmHeapMb,warmRetained:warmLiveHeapMb}};
writeFileSync(root+'/comparison.json',JSON.stringify(report,null,2));
console.log(JSON.stringify(report,null,2));
