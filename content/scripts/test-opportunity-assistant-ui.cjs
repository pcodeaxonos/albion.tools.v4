const assert = require('node:assert/strict');
const { chromium } = require('playwright');
const fs = require('node:fs');
const path = require('node:path');
(async () => {
    const { analyzeMarketCell, assessMarketSide } = await import('../js/core/market-opportunities.mjs');
    const now=Date.now(), fees={setupFeeRate:.025,taxPremiumRate:.04,taxFreeRate:.08};
    const side=(kind,price)=>assessMarketSide({now,points:Array.from({length:30},(_,i)=>({server:'europe',itemId:'T4_BAG',city:'Martlock',quality:1,side:kind,source:'aodp-current',price:i<27?1000:price,sourceQuoteAt:new Date(now-(29-i)*3600000).toISOString(),fetchedAt:new Date(now-(29-i)*3600000).toISOString()}))});
    const row=analyzeMarketCell({server:'europe',itemId:'T4_BAG',city:'Martlock',quality:1,now,fees,buy:side('buy',1000),sell:side('sell',800)});
    const opportunity={...row,primary:row.strategies.find(s=>s.id==='instant-buy-from-sell')};
    let candidates=[opportunity];
    const browser=await chromium.launch({channel:'chrome',headless:true});
    try {
        const context=await browser.newContext({viewport:{width:1440,height:1000},permissions:['clipboard-read','clipboard-write']});
        await context.addInitScript(() => {
            localStorage.setItem('albiontools.v4.dailyBonusRedirectAt',String(Date.now()));
            localStorage.setItem('albiontools.v4.settings',JSON.stringify({dataSync:false,server:'europe',premium:true}));
            if (!localStorage.getItem('opp-layout')) localStorage.setItem('opp-layout','cards');
        });
        const page=await context.newPage(), errors=[];
        page.on('pageerror',e=>errors.push(e.message));
        // Serve the actual workspace files through Playwright when loopback access is restricted.
        const origin=process.env.OPPORTUNITY_TEST_ORIGIN||'http://localhost:3013';
        await page.route('**/*', async route => {
            const requested=new URL(route.request().url());
            if (requested.origin!==origin) return route.abort();
            let relative=decodeURIComponent(requested.pathname).replace(/^\//,'');
            if (!path.extname(relative)) relative=relative.replace(/\/$/,'')+'/index.html';
            const file=path.resolve(relative), root=process.cwd();
            if (!file.startsWith(root+path.sep)) return route.abort();
            if (!fs.existsSync(file)) return route.fulfill({status:404,body:''});
            const types={'.html':'text/html','.js':'text/javascript','.mjs':'text/javascript','.json':'application/json','.css':'text/css','.webp':'image/webp','.png':'image/png','.svg':'image/svg+xml'};
            return route.fulfill({body:fs.readFileSync(file),contentType:types[path.extname(file)]||'application/octet-stream'});
        });
        await page.route('**/api/v1/market/opportunities?**',route=>route.fulfill({json:{server:'europe',engineMode:'validated',scannedAt:new Date().toISOString(),scanned:1,eligibleCandidates:candidates,opportunities:candidates,diagnostics:[],potentialCandidates:[],suspiciousCandidates:[],counts:{verified:candidates.length,potential:0,suspicious:0,insufficient:0,monitored:0},excluded:{},listLimit:500}}));
        await page.route('**/api/v1/market/opportunity-series?**',route=>route.fulfill({json:{buy:{points:[]},sell:{points:[]}}}));
        const url=origin+'/pages/tools/opportunities/';
        await page.goto(url);
        await page.locator('.opp-card').waitFor();
        assert.ok((await page.locator('.opp-card-go').innerText()).includes('Şimdi al'), await page.locator('.opp-card').innerText());
        assert.ok((await page.locator('.opp-reference').first().innerText()).includes('aralık altında'));
        const itemName=page.locator('.opp-card [data-copy-item-name]');
        const fullName=await itemName.getAttribute('data-copy-item-name');
        await itemName.click();
        assert.equal(await page.evaluate(()=>navigator.clipboard.readText()),fullName);
        assert.equal(await page.locator('[data-opportunities-dialog]').evaluate(el=>el.open),false,'copy must not open card');
        await itemName.focus(); await page.keyboard.press('Enter'); await page.keyboard.press('Space');
        assert.equal(await page.evaluate(()=>navigator.clipboard.readText()),fullName);
        await page.locator('[data-watch]').click();
        assert.equal(await page.locator('[data-watch]').getAttribute('aria-pressed'),'true');
        assert.equal(await page.locator('[data-opportunities-dialog]').evaluate(el=>el.open),false,'watch must not open parent card');
        await page.reload(); await page.locator('.opp-card').waitFor();
        assert.equal(await page.locator('[data-watch]').getAttribute('aria-pressed'),'true');
        await page.locator('.opp-card-go').click();
        await page.locator('[data-feedback="correct"]').click();
        await page.locator('[data-feedback="changed"]').click();
        await page.locator('[data-feedback="missing"]').click();
        await page.locator('[data-feedback="executed"]').click();
        assert.ok((await page.locator('[data-feedback-message]').innerText()).includes('kaydedildi'));
        const saved=await page.evaluate(()=>JSON.parse(localStorage.getItem('opp-assistant-v2')));
        assert.equal(saved.feedback.length,4); assert.equal(saved.feedback[0].itemId,'T4_BAG');
        assert.equal(saved.feedback[0].snapshot.sell,800);
        await page.locator('[data-opportunities-close]').click();
        candidates=[{...opportunity,sell:{...opportunity.sell,price:850}}];
        await page.locator('[data-opportunities-refresh]').click();
        await page.waitForFunction(()=>Object.values(JSON.parse(localStorage.getItem('opp-assistant-v2')).watches)[0].last.sell===850);
        const changed=await page.evaluate(()=>Object.values(JSON.parse(localStorage.getItem('opp-assistant-v2')).watches)[0]);
        assert.equal(changed.first.sell,800); assert.equal(changed.changes.length,1);
        await page.locator('[data-filter="watched"]').selectOption('yes');
        assert.equal(await page.locator('.opp-card').count(),1,'watch filter survives presentation strategy change');
        await page.locator('.opp-watch-history summary').click();
        assert.ok((await page.locator('.opp-watch-history').innerText()).includes('850'));
        await page.locator('.opp-watch-history [data-copy-item-name]').click();
        assert.equal(await page.evaluate(()=>navigator.clipboard.readText()),fullName);
        fs.mkdirSync('docs/opportunity-v2',{recursive:true});
        await page.screenshot({path:'docs/opportunity-v2/desktop.png',fullPage:true});
        await page.setViewportSize({width:390,height:844});
        await page.waitForTimeout(350);
        await page.locator('.opp-card').scrollIntoViewIfNeeded();
        assert.ok(await page.evaluate(()=>document.documentElement.scrollWidth<=window.innerWidth),'mobile overflow');
        await page.screenshot({path:'docs/opportunity-v2/mobile.png',fullPage:true});
        candidates=[];
        await page.locator('[data-opportunities-refresh]').click();
        await page.waitForFunction(()=>Object.values(JSON.parse(localStorage.getItem('opp-assistant-v2')).watches)[0].last.status==='ABSENT');
        assert.ok((await page.locator('.opp-watch-history').textContent()).includes('Tarama adayları arasında yok'));
        await page.reload(); await page.locator('.opp-watch-history').waitFor();
        assert.equal((await page.evaluate(()=>JSON.parse(localStorage.getItem('opp-assistant-v2')))).feedback.length,4);
        await page.locator('.opp-watch-history summary').click();
        await page.locator('[data-watch-remove]').click();
        const stopped=await page.evaluate(()=>Object.values(JSON.parse(localStorage.getItem('opp-assistant-v2')).watches)[0]);
        assert.equal(stopped.active,false); assert.equal(stopped.first.sell,800); assert.ok(stopped.changes.length>=2,'stopping keeps history');
        assert.deepEqual(errors,[]);
        console.log('Chrome V2: desktop/mobile, actions, watch isolation/reload, price/absent transitions, feedback persistence and clean console passed.');
    } finally { await browser.close(); }
})().catch(e=>{console.error(e);process.exit(1);});
