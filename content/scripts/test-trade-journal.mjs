import assert from 'node:assert/strict';
import { journalDay, shiftJournalDay, mergeJournalTrades, journalGroups, journalHighlights } from '../js/core/trade-journal.mjs';
const fill = (id, changes = {}) => ({ sourceId: String(id), characterGuid: 'character-a', itemId: 'T4_MAIN_SWORD@1', itemName: 'Sword', clusterIndex: '3005', locationName: 'Martlock', quality: 2, kind: 'instant_sell', occurredAt: '2026-10-14T22:00:00Z', quantity: 2, unitPriceSilver: 100, totalPriceSilver: 200, ...changes });
const day = '2026-10-15';
assert.equal(journalDay('2026-10-14T20:59:59Z'),'2026-10-14');
assert.equal(journalDay('2026-10-14T21:00:00Z'),day);
assert.equal(journalDay('2026-10-15T21:00:00Z'),'2026-10-16');
assert.equal(journalDay('2026-03-29T21:00:00Z'),'2026-03-30');
assert.equal(shiftJournalDay('2026-03-01',-1),'2026-02-28');
let records = mergeJournalTrades(new Map(), [fill(1),fill(2),fill(3,{kind:'instant_buy',totalPriceSilver:120,unitPriceSilver:60})],true);
let model = journalGroups(records,day);
assert.equal(model.sales,400); assert.equal(model.buys,120); assert.equal(model.net,280); assert.equal(model.groups.length,2);
const version = model.groups[0].version;
records = mergeJournalTrades(records,[fill(1),fill(2)]);
assert.equal(journalGroups(records,day).count,3,'duplicate SSE cannot add fills');
assert.equal(journalGroups(records,day).groups[0].version,version);
records = mergeJournalTrades(records,[fill(4)]);
assert.notEqual(journalGroups(records,day).groups[0].version,version,'new partial fill invalidates read version');
const modified = journalGroups(mergeJournalTrades(new Map(),[fill(1,{referencePrice:555})],true),day);
assert.equal(modified.groups[0].version,journalGroups(mergeJournalTrades(new Map(),[fill(1)],true),day).groups[0].version);
const variants = [fill(10),fill(11,{quality:3}),fill(12,{quality:null}),fill(13,{itemId:'T4_MAIN_SWORD@2'}),fill(14,{clusterIndex:'5005'}),fill(15,{characterGuid:'character-b'})];
assert.equal(journalGroups(mergeJournalTrades(new Map(),variants,true),day).groups.length,6);
const late = mergeJournalTrades(records,[fill(20,{occurredAt:'2026-10-13T22:00:00Z'})]);
assert.equal(journalGroups(late,'2026-10-14').count,1);
assert.equal(journalGroups(late,day).count,4);
const invalid = journalGroups(mergeJournalTrades(new Map(),[fill(null,{sourceId:null}),fill(2,{quantity:null}),fill(3,{totalPriceSilver:null}),fill(4,{quality:0}),fill(5,{kind:'mail_sell_expired'}),fill(6,{occurredAt:null})],true),day);
assert.equal(invalid.count,0); assert.equal(invalid.skipped,5); assert.equal(invalid.excluded,1);
assert.equal(journalHighlights(journalGroups(mergeJournalTrades(new Map(),[fill(1)],true),day),()=>true).length,0);
assert.ok(journalHighlights(model,()=>true).every(e=>!e.reason.includes('iptal')));
const many = journalGroups(mergeJournalTrades(new Map(),Array.from({length:100},(_,i)=>fill(i)),true),day);
assert.equal(many.groups.length,1); assert.equal(many.groups[0].quantity,200); assert.equal(many.groups[0].average,100);
assert.equal(journalHighlights(many,()=>true).length,1);
console.log('PASS journal: totals, sides, variants, partial fills, deduplication, versions, late fills, Istanbul boundaries, missing data, conservative highlights');
