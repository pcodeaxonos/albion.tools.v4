import { readFileSync, writeFileSync } from 'node:fs';
import { resolve } from 'node:path';
import { OrderPriceHistory } from '../js/core/order-price-history.mjs';
import { AODP_HISTORY_POLICY } from '../js/core/market-history-config.mjs';
import { shadowEvaluate } from '../js/core/market-opportunity-shadow.mjs';
const root=process.cwd();
const packets=JSON.parse(readFileSync(resolve(root,'.price-order-history.json'),'utf8'));
const archive=JSON.parse(readFileSync(resolve(root,'.aodp-quote-history.json'),'utf8'));
const now=process.argv[2] ? Date.parse(process.argv[2]) : Date.now();
if(!Number.isFinite(now)) throw new Error('Invalid evaluation time');
const servers=JSON.parse(readFileSync(resolve(root,'data/price-servers.json'),'utf8')).map(row=>row.code);
const packetHistory=new OrderPriceHistory({servers});packetHistory.restore(packets,now);
const history=new OrderPriceHistory({servers,source:'aodp-current',policy:AODP_HISTORY_POLICY});history.restore(archive.history,now);
const current=new Map(archive.current || []);
const repository={identities: at=>history.identities(at),seriesFor:(id,at)=>history.seriesFor(id,at),currentQuote:id=>current.get(`${id.server}|${id.itemId}|${id.city}|${id.quality}|${id.side}`)};
const rates=JSON.parse(readFileSync(resolve(root,'data/economy-constants.json'),'utf8'));
const rate=key=>Number(rates.find(row=>row.key===key).value);
const fees={setupFeeRate:rate('setup_fee'),taxPremiumRate:rate('tax_premium'),taxFreeRate:rate('tax_free')};
const results=servers.map(server=>{const {validated,...summary}=shadowEvaluate({server,packetHistory,repository,now,fees});return {server,...summary};});
const out=resolve(root,'docs/market-observation-shadow.json');writeFileSync(out,JSON.stringify({archiveOnly:true,journalIncluded:false,results},null,2));
console.log(JSON.stringify(results.map(({evaluated,oldCandidates,newCandidates,verified,quarantinedCells,changedReferences,removed,added,elapsedMs})=>({evaluated,oldCandidates,newCandidates,verified,quarantinedCells,changedReferences,removed,added,elapsedMs})),null,2));
